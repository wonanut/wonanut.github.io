/**
 * Standalone build for the personal site.
 *
 * The upstream plugin (dsh-plugins/agent-lab-plugin) is a DSH *client plugin*:
 * its 13 source files are concatenated into a factory registered on
 * window.__ModuleLoader__ and rendered inside the DSH web UI, with React
 * injected by the host.
 *
 * For https://wonanut.github.io/agent-lab/ we build the same sources into a
 * plain IIFE that exposes `window.AgentLab.Page`, so the page can be rendered
 * on a static site with a locally vendored React. Only the host registration
 * shell (slots/sidebar) is unused; the lab engine, terminal, inspector,
 * dataflow, docs and source browser are the upstream code verbatim.
 *
 * Usage: node build.mjs [--check] [--commit <sha>]
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

const FILES = [
  ['00-core.js', '常量、token 估算与通用工具'],
  ['10-engine.js', '会话 / 记忆 / 上下文 / 压缩 / createLab'],
  ['20-tools.js', '工具注册表与四个工具'],
  ['30-llm.js', '规则驱动的模拟 LLM'],
  ['40-ui-kit.js', '全局样式与 UI 原语'],
  ['45-real-client.js', '真实模型客户端：状态与模型请求'],
  ['50-tui.js', '模拟 TUI 终端'],
  ['60-inspector.js', '流转 / 上下文 / 记忆检查器'],
  ['65-dataflow.js', 'Agent 数据流转视图（回放）'],
  ['70-docs.js', 'Agent 原理页'],
  ['80-source.js', '源码浏览器'],
  ['90-page.js', '页面外壳与会话栏'],
  ['95-apply.js', 'slot 注册入口（本站未使用）'],
];

const commitArgIndex = process.argv.indexOf('--commit');
const commit = commitArgIndex > 0 ? process.argv[commitArgIndex + 1] : '';

const read = (file) => fs.readFileSync(path.join(root, 'src', file), 'utf8');

const bodySources = FILES.map(([file, role]) => ({
  id: file.replace(/\.js$/, ''),
  name: file,
  role,
  code: read(file),
}));

const hostSource = {
  id: 'index-host',
  name: 'index.js (Host 半侧)',
  role: '真实模型路由：status / complete（调用 DSH 当前 DeepSeek 模型）',
  code: fs.readFileSync(path.join(root, 'host-index.js'), 'utf8'),
};
const sources = bodySources.concat([hostSource]);

const body = bodySources
  .map((source) => `/* ── ${source.name} · ${source.role} ── */\n${source.code}`)
  .join('\n\n');

const meta = {
  name: pkg.name,
  version: pkg.version,
  upstream: 'https://github.com/wonanut/dsh-plugins/tree/main/agent-lab-plugin',
  commit,
  builtAt: new Date().toISOString(),
};

const output = `/* Generated by agent-lab/build.mjs from src/*.js — do not edit by hand.
 * Upstream: https://github.com/wonanut/dsh-plugins/tree/main/agent-lab-plugin${commit ? ' @ ' + commit : ''}
 * License: MIT (see agent-lab/LICENSE). */
(function () {
  "use strict";
  const React = window.React;
  const e = React.createElement;
  const { useState, useEffect, useMemo, useRef, useCallback } = React;
  const SOURCES = ${JSON.stringify(sources)};
  const AGENT_LAB_META = ${JSON.stringify(meta, null, 2)};

${body}

  window.AgentLab = {
    Page,
    sources: SOURCES,
    meta: AGENT_LAB_META,
    mount: function (element) {
      if (!element) throw new Error('mount: element is required');
      const root = window.ReactDOM.createRoot(element);
      root.render(e(Page, {}));
      return root;
    },
  };
})();
`;

const target = path.join(root, 'app.js');
if (process.argv.includes('--check')) {
  new vm.Script(output, { filename: target });
  console.log('[build] syntax OK,', output.length, 'bytes');
  process.exit(0);
}
fs.writeFileSync(target, output);
new vm.Script(output, { filename: target });
console.log(`[build] wrote ${path.relative(process.cwd(), target)} (${output.length} bytes, ${sources.length} sources)`);
